const MTAdmin = (function () {
  "use strict";
  const { qs, qsa, formatCurrency, formatDate, toast, currentLang } = MTUtils;

  // Notifications only ever stored the tour's slug (new records) or just
  // its English name (older records, before the slug was added) - this
  // resolves either into the name in the admin's current language, via
  // the same MT_TOURS data every admin page already loads, falling back
  // to whatever was stored if no match is found.
  function localizedTourName(n) {
    if (typeof MT_TOURS !== "undefined" && n.slug) {
      const t = MT_TOURS.find((x) => x.slug === n.slug);
      if (t) return t.name[currentLang()] || t.name.en;
    }
    return n.tour;
  }

  // The activity log's "action" text is generated by the backend as a
  // fixed set of English strings (some with an embedded dynamic value -
  // a status, a reason, a count). This translates the known static
  // parts; an embedded reason/error message (e.g. a raw SMTP failure)
  // is left as-is since it's free-form diagnostic text, not a fixed
  // piece of UI copy that can be looked up.
  const STATUS_KEY = { Pending: "admin.status_pending", Confirmed: "admin.status_confirmed", Completed: "admin.status_completed", Cancelled: "admin.status_cancelled" };
  function translateActivityAction(action) {
    if (!action) return action;
    const exact = {
      "Reservation Created": "admin.act_reservation_created",
      "Customer confirmation email sent": "admin.act_customer_email_sent",
      "Owner notification email sent": "admin.act_owner_email_sent",
      "Notes Updated": "admin.act_notes_updated",
      "Status update email sent": "admin.act_status_email_sent",
      "Reservation Deleted": "admin.act_reservation_deleted",
    };
    if (exact[action]) return mtT(exact[action]);

    let m = action.match(/^Reservation (Pending|Confirmed|Completed|Cancelled)$/);
    if (m) return `${mtT("admin.act_reservation_status")} ${mtT(STATUS_KEY[m[1]])}`;

    m = action.match(/^Customer email NOT sent \((.+)\)$/);
    if (m) return `${mtT("admin.act_customer_email_failed")} (${m[1]})`;

    m = action.match(/^Owner notification email NOT sent \((.+)\)$/);
    if (m) return `${mtT("admin.act_owner_email_failed")} (${m[1]})`;

    m = action.match(/^Status update email NOT sent \((.+)\)$/);
    if (m) return `${mtT("admin.act_status_email_failed")} (${m[1]})`;

    m = action.match(/^Customer Deleted \((\d+) reservations? removed\)$/);
    if (m) return `${mtT("admin.act_customer_deleted")} (${m[1]} ${mtT("admin.act_reservations_removed")})`;

    return action; // unrecognized - show as-is rather than hide it
  }

  // The backend always stores/returns status as one of these 4 fixed
  // English values (it's the data value, not display copy - filters and
  // <option> values compare against it directly). Anywhere it's shown to
  // a person, it needs to go through this first.
  function statusLabel(status) {
    return mtT(STATUS_KEY[status] || "admin.status_pending");
  }

  /**
   * Every admin page calls this first. Returns true and lets the page
   * proceed if the backend is reachable and the session is valid.
   * Otherwise it renders a clear, honest error state into the page's
   * main content area and returns false so the page's own script can
   * stop immediately instead of rendering with no data.
   */
  async function requireBackend(contentSelector) {
    const token = MTUtils.getAdminToken();
    if (!token) {
      redirectToLogin();
      return false;
    }
    let reachable = false;
    try {
      reachable = await MTApi.isAvailable();
    } catch (e) {
      reachable = false;
    }
    if (!reachable) {
      renderBackendError(contentSelector, "backend_unreachable");
      return false;
    }
    return true;
  }

  function redirectToLogin() {
    const here = encodeURIComponent(location.pathname.split("/").pop());
    location.href = `login.html?next=${here}`;
  }

  function renderBackendError(contentSelector, kind) {
    const target = contentSelector ? qs(contentSelector) : null;
    const isFileProtocol = typeof MT_IS_FILE_PROTOCOL !== "undefined" && MT_IS_FILE_PROTOCOL;
    const connectDetail = isFileProtocol
      ? `${mtT("admin.error_file_protocol_detail")} <code>cd backend && node server.js</code>, ${mtT("admin.error_file_protocol_detail2")} <code>cd site && python3 -m http.server 8000</code> (backend/README.md).`
      : `${mtT("admin.error_cannot_connect_detail")} <code>${typeof MT_API_BASE !== "undefined" ? MT_API_BASE : "(unknown)"}</code>. <code>cd backend && node server.js</code> (backend/README.md).`;
    const messages = {
      backend_unreachable: {
        title: mtT("admin.error_cannot_connect_title"),
        body: mtT("admin.error_cannot_connect_body"),
        detail: connectDetail,
      },
      session_expired: {
        title: mtT("admin.error_session_title"),
        body: mtT("admin.error_session_body"),
        detail: "",
      },
    };
    const m = messages[kind] || messages.backend_unreachable;
    const html = `
      <div class="panel" style="text-align:center; padding:64px 32px;">
        <div style="width:64px; height:64px; border-radius:50%; background:var(--danger-100); color:var(--danger-600); display:flex; align-items:center; justify-content:center; margin:0 auto 20px;">
          <svg width="30" height="30" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="m10.29 3.86-8.18 14.14A2 2 0 0 0 3.82 21h16.36a2 2 0 0 0 1.71-3L13.71 3.86a2 2 0 0 0-3.42 0Z"/><line x1="12" y1="9" x2="12" y2="13"/><line x1="12" y1="17" x2="12.01" y2="17"/></svg>
        </div>
        <h3 style="margin-bottom:10px;">${m.title}</h3>
        <p style="max-width:480px; margin:0 auto 8px;">${m.body}</p>
        <p style="max-width:480px; margin:0 auto; font-size:.85rem; color:var(--slate-400);">${m.detail}</p>
        <button type="button" class="btn btn--primary" style="margin-top:24px;" onclick="location.reload()">${mtT("admin.try_again")}</button>
      </div>`;
    if (target) target.innerHTML = html;
    const badge = qs("#globalDataSourceBadge");
    if (badge) {
      badge.textContent = mtT("admin.backend_unavailable");
      badge.className = "badge badge--danger";
    }
  }

  /* ---------------- Notifications (real backend only) ---------------- */
  async function loadAndRenderNotifications() {
    const panel = qs("#adminNotifPanel");
    const dot = qs(".admin-notif__dot");
    if (!panel) return;
    if (!MTUtils.getAdminToken()) return; // not logged in - the page's own requireBackend() handles the redirect
    try {
      const { notifications, unreadCount } = await MTApi.getNotifications();
      if (dot) dot.style.display = unreadCount > 0 ? "block" : "none";
      const header = `<div style="padding:10px 12px; font-weight:800; font-size:.85rem; color:var(--navy-900);">${mtT("admin.recent_notifications")}</div>`;
      const items = notifications.slice(0, 6).map((n) => `
        <button class="tb-dropdown__item" style="align-items:flex-start;" data-notif-goto="${n.reservationId}">
          ${iconBell()}<span><strong>${MTUtils.escapeHtml(n.customer)}</strong> ${mtT("admin.notif_booked")} ${MTUtils.escapeHtml(localizedTourName(n))}<br><span style="color:var(--slate-400); font-size:.72rem;">${timeAgo(n.createdAt)}</span></span>
        </button>`).join("");
      panel.innerHTML = header + (items || `<div style="padding:16px 12px; font-size:.82rem; color:var(--slate-400);">${mtT("admin.no_notifications")}</div>`);
      qsa("[data-notif-goto]", panel).forEach((btn) => {
        btn.addEventListener("click", () => { location.href = `reservations.html?search=${encodeURIComponent(btn.dataset.notifGoto)}`; });
      });
    } catch (err) {
      const panelEl = qs("#adminNotifPanel");
      if (panelEl) panelEl.innerHTML = `<div style="padding:16px 12px; font-size:.82rem; color:var(--danger-600);">${mtT("admin.err_load_notifications_unreachable")}</div>`;
    }
  }

  function iconBell() {
    return '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M18 8a6 6 0 0 0-12 0c0 7-3 9-3 9h18s-3-2-3-9"/><path d="M13.7 21a2 2 0 0 1-3.4 0"/></svg>';
  }
  function timeAgo(iso) {
    const diffMs = Date.now() - new Date(iso).getTime();
    const mins = Math.floor(diffMs / 60000);
    if (mins < 1) return mtT("admin.time_just_now");
    if (mins < 60) return mins + " " + mtT("admin.time_min_ago");
    const hrs = Math.floor(mins / 60);
    if (hrs < 24) return hrs + " " + mtT("admin.time_hr_ago");
    return Math.floor(hrs / 24) + " " + mtT("admin.time_day_ago");
  }

  /* ---------------- Sidebar / topbar chrome ---------------- */
  function initChrome() {
    const badge = qs("#globalDataSourceBadge");
    if (badge) { badge.textContent = mtT("admin.connected"); badge.className = "badge badge--teal"; }

    // Universal modal close handling for every admin page - the X button,
    // any element marked [data-modal-close] or [data-delete-cancel]
    // (page-specific Cancel buttons), and clicking the dimmed backdrop
    // itself all close whichever modal(s) are currently open. ESC does
    // the same. This used to only exist on the Reservations page (each
    // other page had no close wiring at all, which is why the X button
    // sometimes silently did nothing) - now it's shared, so every admin
    // page's modals behave identically without needing their own copy.
    function closeAllOpenModals() {
      qsa(".modal-overlay.is-open").forEach((m) => m.classList.remove("is-open"));
    }
    document.addEventListener("click", (e) => {
      if (e.target.matches("[data-modal-close]") || e.target.closest("[data-modal-close]") || e.target.matches("[data-delete-cancel]") || e.target.classList.contains("modal-overlay")) {
        closeAllOpenModals();
      }
    });
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape") closeAllOpenModals();
    });

    const burger = qs("#adminBurger");
    const sidebar = qs("#adminSidebar");
    burger && burger.addEventListener("click", () => sidebar.classList.toggle("is-open"));
    document.addEventListener("click", (e) => {
      if (sidebar && sidebar.classList.contains("is-open") && !sidebar.contains(e.target) && e.target !== burger) {
        sidebar.classList.remove("is-open");
      }
    });
    const notifBtn = qs("#adminNotifBtn");
    const notifPanel = qs("#adminNotifPanel");
    const notifWrap = qs("#adminNotifWrap");
    if (notifBtn && notifPanel && notifWrap) {
      loadAndRenderNotifications();
      notifBtn.addEventListener("click", async (e) => {
        e.stopPropagation();
        const willOpen = !notifWrap.classList.contains("is-open");
        notifWrap.classList.toggle("is-open");
        if (willOpen) {
          try { await MTApi.markNotificationsRead(); loadAndRenderNotifications(); } catch (err) { /* non-fatal */ }
        }
      });
      document.addEventListener("click", () => notifWrap.classList.remove("is-open"));
    }
    qsa("[data-admin-logout]").forEach((l) => l.addEventListener("click", (e) => {
      e.preventDefault();
      MTUtils.clearAdminToken();
      sessionStorage.removeItem("mt_admin_session");
      location.href = "login.html";
    }));
  }

  /* ---------------- Simple SVG chart helpers (pure functions, no data source) ---------------- */
  function lineChart(svgEl, points, opts) {
    opts = opts || {};
    const w = opts.width || 560, h = opts.height || 200, pad = 24;
    const max = Math.max(...points, 1);
    const min = Math.min(...points, 0);
    const range = (max - min) || 1;
    const stepX = (w - pad * 2) / (points.length - 1 || 1);
    const coords = points.map((p, i) => {
      const x = pad + i * stepX;
      const y = h - pad - ((p - min) / range) * (h - pad * 2);
      return [x, y];
    });
    const linePath = coords.map((c, i) => (i === 0 ? "M" : "L") + c[0].toFixed(1) + "," + c[1].toFixed(1)).join(" ");
    const areaPath = coords.length ? linePath + ` L${coords[coords.length - 1][0]},${h - pad} L${coords[0][0]},${h - pad} Z` : "";
    const dots = coords.map((c) => `<circle class="chart-tooltip-dot" cx="${c[0].toFixed(1)}" cy="${c[1].toFixed(1)}" r="4" fill="var(--teal-500)" stroke="#fff" stroke-width="2"/>`).join("");
    svgEl.setAttribute("viewBox", `0 0 ${w} ${h}`);
    svgEl.classList.add("chart-svg");
    svgEl.innerHTML = `
      <defs>
        <linearGradient id="lineFill" x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stop-color="var(--teal-400)" stop-opacity="0.35"/>
          <stop offset="100%" stop-color="var(--teal-400)" stop-opacity="0"/>
        </linearGradient>
      </defs>
      <path d="${areaPath}" fill="url(#lineFill)" stroke="none"/>
      <path d="${linePath}" fill="none" stroke="var(--teal-500)" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"/>
      ${dots}
    `;
  }

  function donutChart(svgEl, segments) {
    const total = segments.reduce((s, seg) => s + seg.value, 0) || 1;
    const size = 160, r = 58, cx = size / 2, cy = size / 2, sw = 22;
    const circumference = 2 * Math.PI * r;
    let offset = 0;
    const circles = segments.map((seg) => {
      const frac = seg.value / total;
      const dash = frac * circumference;
      const el = `<circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${seg.color}" stroke-width="${sw}"
        stroke-dasharray="${dash.toFixed(2)} ${(circumference - dash).toFixed(2)}"
        stroke-dashoffset="${(-offset).toFixed(2)}" transform="rotate(-90 ${cx} ${cy})" stroke-linecap="butt"/>`;
      offset += dash;
      return el;
    }).join("");
    svgEl.setAttribute("viewBox", `0 0 ${size} ${size}`);
    svgEl.classList.add("chart-svg", "donut-chart");
    svgEl.innerHTML = circles;
  }

  /* ---------------- Generic table helpers (pure functions) ---------------- */
  function paginate(items, page, perPage) {
    const start = (page - 1) * perPage;
    return items.slice(start, start + perPage);
  }

  function buildPagination(container, total, page, perPage, onChange) {
    const pages = Math.max(1, Math.ceil(total / perPage));
    container.innerHTML = "";
    const mk = (label, target, disabled, active) => {
      const b = document.createElement("button");
      b.textContent = label;
      b.disabled = disabled;
      if (active) b.classList.add("is-active");
      b.addEventListener("click", () => onChange(target));
      return b;
    };
    container.appendChild(mk("\u2039", page - 1, page <= 1, false));
    for (let i = 1; i <= pages; i++) {
      if (pages > 7 && i > 2 && i < pages - 1 && Math.abs(i - page) > 1) {
        if (i === 3 || i === pages - 2) {
          const span = document.createElement("span");
          span.textContent = "\u2026";
          span.style.padding = "0 6px";
          container.appendChild(span);
        }
        continue;
      }
      container.appendChild(mk(String(i), i, false, i === page));
    }
    container.appendChild(mk("\u203A", page + 1, page >= pages, false));
  }

  document.addEventListener("DOMContentLoaded", initChrome);

  return {
    requireBackend, renderBackendError, redirectToLogin,
    lineChart, donutChart, paginate, buildPagination,
    loadAndRenderNotifications, timeAgo, localizedTourName, translateActivityAction, statusLabel,
  };
})();
